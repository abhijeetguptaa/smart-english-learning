/**
 * Returns the YouTube Short video ID for a given word or letter.
 */
export function getShortForWord(word: string, letter?: string): string {
  const normalized = word.toLowerCase().replace(/[^a-z]/g, '');
  if (WORD_SHORTS_MAP[normalized]) {
    return WORD_SHORTS_MAP[normalized];
  }
  // Substring search
  for (const [key, id] of Object.entries(WORD_SHORTS_MAP)) {
    if (normalized.includes(key) || key.includes(normalized)) {
      return id;
    }
  }
  const firstLetter = (letter || word.charAt(0)).toUpperCase();
  return LETTER_FALLBACK_SHORTS[firstLetter] || '_Rv5t_84K-A';
}

/**
 * Builds the official embed URL for a YouTube Short with autoplay and origin parameters.
 */
export function getShortEmbedUrl(videoId: string): string {
  const url = new URL(`https://www.youtube.com/embed/${videoId}`);
  url.searchParams.set('autoplay', '1');
  url.searchParams.set('rel', '0');
  url.searchParams.set('playsinline', '1');
  url.searchParams.set('modestbranding', '1');
  url.searchParams.set('enablejsapi', '1');
  url.searchParams.set('iv_load_policy', '3');
  if (typeof window !== 'undefined' && window.location.origin.startsWith('http')) {
    url.searchParams.set('origin', window.location.origin);
  }
  return url.toString();
}
